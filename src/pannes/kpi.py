"""Reliability KPIs as SQL views (the layer a Power BI report connects to).

    v_pannes_detail      one row per breakdown with equipment, site, part, declaration delay (h),
                         repair duration (h) and a late-declaration flag
    v_kpi_piece          per part: breakdowns, equipment affected, breakdowns per month, MTTR (h),
                         share of critical breakdowns
    v_kpi_equipement     per machine: breakdowns, MTTR (h), MTBF (h) over the observed period,
                         availability = 1 - repair time / observed time
    v_kpi_mensuel        per month and site: breakdowns, mean declaration delay (h), share of
                         late declarations (> LATE_DECLARATION_HOURS)

The views are generated per dialect (only date arithmetic differs) and also written as T-SQL in
sql/sqlserver/views.sql.
"""
from __future__ import annotations

from sqlalchemy import Engine, text

from .config import LATE_DECLARATION_HOURS
from .db import hours_between


def _month(dialect: str, col: str) -> str:
    if dialect == "sqlite":
        return f"strftime('%Y-%m', {col})"
    if dialect == "mssql":
        return f"CONVERT(char(7), {col}, 126)"
    return f"to_char({col}, 'YYYY-MM')"


def view_sql(dialect: str) -> dict[str, str]:
    decl = hours_between(dialect, "p.date_panne", "p.date_declaration")
    rep = hours_between(dialect, "p.date_panne", "p.date_fin")
    span = hours_between(dialect, "(select min(date_panne) from pannes)",
                         "(select max(date_panne) from pannes)")
    month = _month(dialect, "date_panne")
    late = LATE_DECLARATION_HOURS
    return {
        "v_pannes_detail": f"""
SELECT p.panne_id, p.date_panne, {month.replace('date_panne', 'p.date_panne')} AS mois,
       e.code AS equipement, e.designation AS type_equipement, s.nom AS site,
       pc.nom AS piece, p.gravite, p.source,
       {decl} AS delai_declaration_h,
       {rep} AS duree_reparation_h,
       CASE WHEN p.date_declaration IS NOT NULL AND {decl} > {late} THEN 1 ELSE 0 END
           AS declaration_tardive
FROM pannes p
JOIN equipements e ON e.equipement_id = p.equipement_id
JOIN sites s ON s.site_id = e.site_id
JOIN pieces pc ON pc.piece_id = p.piece_id""",
        "v_kpi_piece": f"""
SELECT piece,
       COUNT(*) AS nb_pannes,
       COUNT(DISTINCT equipement) AS nb_equipements_touches,
       COUNT(*) / (({span}) / (24.0 * 30.4375)) AS pannes_par_mois,
       AVG(duree_reparation_h) AS mttr_h,
       AVG(CASE WHEN gravite = 'critique' THEN 1.0 ELSE 0.0 END) AS part_critique
FROM v_pannes_detail
GROUP BY piece""",
        "v_kpi_equipement": f"""
SELECT equipement, type_equipement, site,
       COUNT(*) AS nb_pannes,
       AVG(duree_reparation_h) AS mttr_h,
       (({span}) - SUM(COALESCE(duree_reparation_h, 0))) / COUNT(*) AS mtbf_h,
       1.0 - SUM(COALESCE(duree_reparation_h, 0)) / ({span}) AS disponibilite
FROM v_pannes_detail
GROUP BY equipement, type_equipement, site""",
        "v_kpi_mensuel": """
SELECT mois, site,
       COUNT(*) AS nb_pannes,
       AVG(delai_declaration_h) AS delai_moyen_h,
       AVG(1.0 * declaration_tardive) AS part_tardives
FROM v_pannes_detail
GROUP BY mois, site""",
    }


VIEW_ORDER = ["v_pannes_detail", "v_kpi_piece", "v_kpi_equipement", "v_kpi_mensuel"]


def create_views(engine: Engine) -> list[str]:
    sqls = view_sql(engine.dialect.name)
    with engine.begin() as con:
        for name in reversed(VIEW_ORDER):
            con.execute(text(f"DROP VIEW IF EXISTS {name}"))
        for name in VIEW_ORDER:
            con.execute(text(f"CREATE VIEW {name} AS{sqls[name]}"))
    return VIEW_ORDER


def sqlserver_views() -> str:
    sqls = view_sql("mssql")
    out = ["-- Generated by `pannes ddl` from src/pannes/kpi.py. Do not edit by hand."]
    for name in VIEW_ORDER:
        out.append(f"CREATE OR ALTER VIEW {name} AS{sqls[name]};\nGO")
    return "\n\n".join(out) + "\n"


def kpi_summary(engine: Engine) -> dict:
    with engine.connect() as con:
        def q(sql):
            return con.execute(text(sql)).mappings().all()

        overall = q("""select count(*) as nb_pannes, avg(delai_declaration_h) as delai_moyen_h,
                              avg(1.0 * declaration_tardive) as part_tardives,
                              avg(duree_reparation_h) as mttr_h
                       from v_pannes_detail""")[0]
        by_source = q("""select source, count(*) as n, avg(1.0 * declaration_tardive) as tardives
                         from v_pannes_detail group by source""")
        top = q("select * from v_kpi_piece order by nb_pannes desc")
        eq = q("""select avg(mtbf_h) as mtbf_moyen_h, avg(disponibilite) as dispo_moyenne,
                         min(disponibilite) as dispo_min from v_kpi_equipement""")[0]
    r4 = lambda v: None if v is None else round(float(v), 4)  # noqa: E731
    return {
        "nb_pannes": int(overall["nb_pannes"]),
        "delai_moyen_declaration_h": r4(overall["delai_moyen_h"]),
        "part_declarations_tardives": r4(overall["part_tardives"]),
        "mttr_h": r4(overall["mttr_h"]),
        "mtbf_moyen_h": r4(eq["mtbf_moyen_h"]),
        "disponibilite_moyenne": r4(eq["dispo_moyenne"]),
        "disponibilite_min": r4(eq["dispo_min"]),
        "par_source": {r["source"]: {"n": int(r["n"]), "part_tardives": r4(r["tardives"])}
                       for r in by_source},
        "par_piece": [{"piece": r["piece"], "nb_pannes": int(r["nb_pannes"]),
                       "pannes_par_mois": r4(r["pannes_par_mois"]), "mttr_h": r4(r["mttr_h"])}
                      for r in top],
    }


def plot_kpis(engine: Engine, out_path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import pandas as pd

    BLUE, ORANGE = "#2a78d6", "#eb6834"
    SURFACE, INK, INK_2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"
    plt.rcParams.update({
        "figure.facecolor": SURFACE, "axes.facecolor": SURFACE, "savefig.facecolor": SURFACE,
        "axes.edgecolor": GRID, "axes.labelcolor": INK_2, "xtick.color": INK_2,
        "ytick.color": INK_2, "text.color": INK, "axes.spines.top": False,
        "axes.spines.right": False, "axes.grid": True, "grid.color": GRID, "font.size": 10,
        "axes.axisbelow": True})
    with engine.connect() as con:
        piece = pd.read_sql(text("select * from v_kpi_piece order by pannes_par_mois"), con)
        month = pd.read_sql(text("""select mois, count(*) as n,
                                           avg(1.0 * declaration_tardive) as part_tardives
                                    from v_pannes_detail group by mois order by mois"""), con)
    fig, axes = plt.subplots(1, 2, figsize=(11.5, 4.6), gridspec_kw={"width_ratios": [1, 1.2]})
    ax = axes[0]
    ax.barh(piece["piece"], piece["pannes_par_mois"], color=BLUE, height=0.62)
    for y, v in enumerate(piece["pannes_par_mois"]):
        ax.text(v, y, f" {v:.1f}", va="center", fontsize=8, color=INK_2)
    ax.set_xlabel("Breakdowns per month (all machines)")
    ax.tick_params(axis="y", labelsize=8)
    ax.grid(axis="y", visible=False)
    _title(ax, "Failure frequency by part", "which parts to stock and inspect first", INK, INK_2)

    ax = axes[1]                                     # all sites: per-site months are too thin
    x = range(len(month))
    ax.plot(x, month["part_tardives"] * 100, "-o", color=ORANGE, lw=2, ms=4)
    mean = (month["part_tardives"] * month["n"]).sum() / month["n"].sum() * 100
    ax.axhline(mean, color=INK_2, lw=1, ls=(0, (4, 3)))
    ax.text(len(month) - 0.5, mean, f" mean {mean:.0f} %", va="bottom", ha="right", fontsize=8,
            color=INK_2)
    ax.set_ylabel(f"% declared more than {LATE_DECLARATION_HOURS:g} h late")
    ticks = list(range(0, len(month), 3))
    ax.set_xticks(ticks)
    ax.set_xticklabels([month["mois"].iloc[i] for i in ticks], fontsize=8)
    ax.set_ylim(bottom=0)
    _title(ax, "Late declarations by month", "all sites; the problem the Flask app targets",
           INK, INK_2)
    fig.tight_layout()
    fig.savefig(out_path, dpi=140)
    plt.close(fig)


def _title(ax, main, sub, ink, ink2):
    ax.set_title(main, loc="left", fontsize=12, fontweight="bold", color=ink, pad=22)
    ax.text(0, 1.03, sub, transform=ax.transAxes, fontsize=9, color=ink2, va="bottom")
